"""Generate the flash-resident alias catalog without changing public commands."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPONENT = ROOT / "components" / "yamaha_serial"


def render(catalog):
    strings = {}
    entries = []
    offset = 0
    names = set()
    for command in sorted(catalog["commands"], key=lambda item: item["name"]):
        name = command["name"]
        if name in names:
            raise ValueError(f"Duplicate command alias: {name}")
        names.add(name)
        if command["frame"] not in ("STX", "DC4"):
            raise ValueError(f"Invalid frame: {name}")
        for value in (name, command["payload"]):
            if not value.isascii() or "\0" in value:
                raise ValueError(f"Invalid catalog string: {name}")
            if value not in strings:
                strings[value] = offset
                offset += len(value) + 1
        entries.append(
            f"    {{{strings[name]}, {strings[command['payload']]}, "
            f"{2 if command['frame'] == 'STX' else 20}, {int(command['response'])}}},"
        )
    if offset > 65535:
        raise ValueError("Command string pool exceeds 16-bit offsets")
    literals = "\n".join(f"    {json.dumps(value)[:-1]}\\0\"" for value in strings)
    return (
        "// SPDX-License-Identifier: GPL-3.0-only\n"
        "// Generated by tools/generate_catalog.py. Edit command_catalog.json.\n"
        "#ifdef YAMAHA_SERIAL_CATALOG_IMPL\n\n"
        "static const char COMMAND_STRINGS[] YAMAHA_SERIAL_FLASH_TABLE =\n"
        f"{literals};\n\n"
        "static const CatalogEntry COMMAND_ALIASES[] YAMAHA_SERIAL_FLASH_TABLE = {\n"
        + "\n".join(entries)
        + "\n};\n#endif\n"
    )


def render_selects(catalog):
    commands, reports = [], []
    for name, group in catalog["selects"].items():
        options = group["options"]
        if len(set(options)) != len(options) or not set(group["reports"].values()) <= set(options):
            raise ValueError(f"Invalid select options/reports: {name}")
        commands.append(f"static const LabelCommand {name.upper()}_COMMANDS[] YAMAHA_SERIAL_FLASH_TABLE = {{")
        commands.extend(f'    {{"{key}", "{payload}"}},' for key, payload in group["commands"].items())
        commands.append("};")
        reports.append(f"static const ReportLabel {name.upper()}_REPORTS[] YAMAHA_SERIAL_FLASH_TABLE = {{")
        reports.extend(f'    {{0x{int(code):02X}, "{label}"}},' for code, label in group["reports"].items())
        reports.append("};")
    return (
        "// SPDX-License-Identifier: GPL-3.0-only\n"
        "// Generated by tools/generate_catalog.py. Edit select_catalog.json.\n"
        "#ifdef YAMAHA_SERIAL_SELECT_COMMANDS\n" + "\n".join(commands) + "\n#endif\n"
        "#ifdef YAMAHA_SERIAL_SELECT_REPORTS\n" + "\n".join(reports) + "\n#endif\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, renderer in (("command", render), ("select", render_selects)):
        catalog = json.loads((COMPONENT / f"{name}_catalog.json").read_text())
        generated = renderer(catalog)
        target = COMPONENT / f"{name}_catalog.generated.h"
        if args.check:
            if not target.is_file() or target.read_text() != generated:
                raise SystemExit(f"{name} catalog is stale; run tools/generate_catalog.py")
        else:
            target.write_text(generated)


if __name__ == "__main__":
    main()
